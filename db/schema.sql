-- 用户资料、商铺、消费券和订单保存于 MySQL，验证码和会话存 Redis。
CREATE TABLE IF NOT EXISTS tb_user (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    phone VARCHAR(11) NOT NULL,
    password VARCHAR(128) DEFAULT '',
    nick_name VARCHAR(32) DEFAULT '',
    icon VARCHAR(255) DEFAULT '',
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uniqe_key_phone (phone)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS tb_voucher (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    shop_id BIGINT UNSIGNED DEFAULT NULL,
    title VARCHAR(255) NOT NULL,
    sub_title VARCHAR(255) DEFAULT NULL,
    rules VARCHAR(1024) DEFAULT NULL,
    pay_value BIGINT UNSIGNED NOT NULL COMMENT '支付金额，单位：分',
    actual_value BIGINT NOT NULL COMMENT '抵扣金额，单位：分',
    status TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '1：上架；2：下架；3：过期',
    stock INT NOT NULL COMMENT '剩余库存，MySQL 事务扣减或关闭回补',
    begin_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS tb_voucher_order (
    id BIGINT NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    voucher_id BIGINT UNSIGNED NOT NULL,
    amount BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '下单金额快照，分',
    reserved_at DATETIME(3) NULL DEFAULT NULL COMMENT 'Redis 预扣时间，UTC；历史订单为空',
    expire_at DATETIME(3) NULL DEFAULT NULL COMMENT '固定支付截止时间，UTC；历史订单为空',
    pay_type TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '1：余额；2：支付宝；3：微信',
    status TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '1：未支付；2：已支付；3：已核销；4：已取消；5：退款中；6：已退款',
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    pay_time TIMESTAMP(3) NULL DEFAULT NULL,
    use_time TIMESTAMP NULL DEFAULT NULL,
    refund_time TIMESTAMP NULL DEFAULT NULL,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS tb_user_info (
    user_id BIGINT UNSIGNED NOT NULL,
    city VARCHAR(64) DEFAULT '',
    introduce VARCHAR(128) DEFAULT NULL,
    fans INT UNSIGNED DEFAULT 0,
    followee INT UNSIGNED DEFAULT 0,
    gender TINYINT UNSIGNED DEFAULT 0,
    birthday DATE DEFAULT NULL,
    credits INT UNSIGNED DEFAULT 0,
    level TINYINT UNSIGNED DEFAULT 0,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS tb_shop (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    name VARCHAR(128) NOT NULL,
    type_id BIGINT UNSIGNED NOT NULL,
    images VARCHAR(1024) NOT NULL,
    area VARCHAR(128) DEFAULT NULL,
    address VARCHAR(255) NOT NULL,
    x DOUBLE UNSIGNED NOT NULL,
    y DOUBLE UNSIGNED NOT NULL,
    avg_price BIGINT UNSIGNED DEFAULT NULL,
    sold INT UNSIGNED NOT NULL,
    comments INT UNSIGNED NOT NULL,
    score INT UNSIGNED NOT NULL,
    open_hours VARCHAR(32) DEFAULT NULL,
    create_time TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY foreign_key_type (type_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
